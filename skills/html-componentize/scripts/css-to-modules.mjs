#!/usr/bin/env node
// PHASE 4 (styling) — css-to-modules. Authored CSS → scoped *.module.css + classMap
//
// THE structural guard against the "inline every computed style" failure:
// we MOVE the authored rules verbatim (selectors, cascade, pseudos, media all
// intact) into a CSS Module. We do NOT read getComputedStyle. We do NOT
// regenerate declarations. Components then reference styles[className].
//
// Given a set of class names (a component's scope), emit only the rules that
// touch those classes; element-only / :root / universal rules are split out as
// "globals" for a global stylesheet. Cross-scope class refs are flagged.
//
// Usage:
//   node css-to-modules.mjs --map source-map.json --classes "card,card-title" \
//        --out src/components/Card.module.css [--globals src/global.css]

import { resolve } from 'node:path';
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import postcss from 'postcss';
import selectorParser from 'postcss-selector-parser';
import { parseArgs, readJSON } from './lib/domtree.mjs';

const args = parseArgs(process.argv.slice(2));
const mapPath = resolve(args.map || '.componentize/source-map.json');
const outPath = resolve(args.out || '.componentize/out.module.css');
const sm = await readJSON(mapPath);

let scope;
if (args.classes) scope = new Set(String(args.classes).split(',').map((s) => s.trim()).filter(Boolean));
else if (args.classesFrom) scope = new Set(await readJSON(resolve(args.classesFrom)));
else scope = new Set(sm.classInventory); // default: whole page → one module

function classesInSelector(sel) {
  const out = [];
  try {
    selectorParser((sels) => {
      sels.walkClasses((c) => out.push(c.value));
    }).processSync(sel);
  } catch { /* ignore unparsable */ }
  return out;
}

const moduleChunks = [];
const globalChunks = [];
const usedClasses = new Set();
const crossScope = new Set(); // classes referenced by kept rules but outside scope
let kept = 0, globals = 0;

// Rebuild from raw CSS so media/order/cascade survive untouched.
for (const src of sm.source.cssSources || []) { /* origins only; raw lives below */ }
// We need raw CSS again: re-read from rules' raw is lossy for media; instead
// reconstruct by walking rules grouped by media context recorded in phase 1.
const byMedia = new Map(); // media|null -> array of raw rule strings (module)
const byMediaGlobal = new Map();
function push(map, media, raw) {
  if (!map.has(media)) map.set(media, []);
  map.get(media).push(raw);
}

for (const r of sm.css.rules || []) {
  if (r.parseError) continue;
  const cls = classesInSelector(r.selector);
  const inScope = cls.some((c) => scope.has(c));
  const hasClass = cls.length > 0;
  if (inScope) {
    push(byMedia, r.media, r.raw);
    kept++;
    cls.forEach((c) => { if (scope.has(c)) usedClasses.add(c); else crossScope.add(c); });
  } else if (!hasClass) {
    push(byMediaGlobal, r.media, r.raw);
    globals++;
  }
}

function render(map) {
  const out = [];
  // plain (no media) first, then media blocks
  if (map.has(null)) out.push(map.get(null).join('\n'));
  for (const [media, rules] of map) {
    if (media === null) continue;
    out.push(`${media} {\n${rules.map((x) => '  ' + x.replace(/\n/g, '\n  ')).join('\n')}\n}`);
  }
  return out.join('\n\n') + '\n';
}

const moduleCss = render(byMedia);
await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, `/* generated by html-componentize — authored rules moved verbatim */\n${moduleCss}`, 'utf8');

if (args.globals && byMediaGlobal.size) {
  const gp = resolve(args.globals);
  await mkdir(dirname(gp), { recursive: true });
  await writeFile(gp, `/* global / element / :root rules (not class-scoped) */\n${render(byMediaGlobal)}`, 'utf8');
}

// classMap: original class -> module reference key (kept identical; CSS Modules
// localizes the name at build time). Only classes that actually have rules.
const classMap = {};
for (const c of scope) if (usedClasses.has(c)) classMap[c] = c;

const unstyled = [...scope].filter((c) => !usedClasses.has(c));

console.log(JSON.stringify({
  ok: true,
  out: outPath,
  globals: args.globals && byMediaGlobal.size ? resolve(args.globals) : null,
  rulesKept: kept,
  globalRules: globals,
  classMap,
  unstyledClasses: unstyled,
  crossScopeRefs: [...crossScope],
}, null, 2));
